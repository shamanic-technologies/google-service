import type { GmailMessage } from "./google-api";
import { extractMessageBody, type BodyStatus } from "./message-body";
import { STAFF_ADDRESSES } from "../lib/staff-mailboxes";

// Mail addressed TO (or sent FROM) our own sending mailboxes, read out of the STAFF Gmail mirrors.
//
// Why it exists: several cold-email sending domains carried a forward on the
// mailbox's own address that redirected every inbound message into a staff Gmail
// WITHOUT keeping a copy. The outreach side reads those mailboxes over IMAP and
// found them empty; every prospect reply from that period exists only here. The
// staff exchange read (getStaffConversation) cannot see them: they are between a
// person and one of OUR SENDING ALIASES, not a staff address.
//
// Narrow by construction:
//   - only mailboxes whose Google account is a STAFF address (same rule as the
//     staff exchange read), whichever org mirrors them;
//   - only messages whose To/Cc holds one of the requested addresses (or an
//     address at a requested domain), or SENT FROM one of them (staff answering
//     via send-as); the filter is in the SQL;
//   - a staff address, or the domain of one, is refused as a filter: asking for
//     "mail to gmail.com" would be the whole staff mailbox.
// A read, never a fetch: zero Google calls; the body is derived from the stored
// payload. No cleaning and no judgment (the caller classifies).

export const MAX_ADDRESSES = 1000;
export const MAX_DOMAINS = 50;
export const DEFAULT_PAGE_LIMIT = 200;

export interface AddressedMessagesInput {
  addresses?: string[];
  domains?: string[];
  since?: string;
  until?: string;
  limit?: number;
  cursor?: string;
}

export interface AutomationHeaders {
  autoSubmitted: string | null;
  precedence: string | null;
  xAutoreply: string | null;
  xAutorespond: string | null;
  xAutoResponseSuppress: string | null;
  xAutogenerated: string | null;
  xFailedRecipients: string | null;
  listId: string | null;
  listUnsubscribe: string | null;
  returnPath: string | null;
  contentType: string | null;
}

export interface AddressedMessage {
  // Stable id of the message in the mirror: unique per (mailbox, gmailMessageId).
  id: string;
  mailbox: string;
  gmailMessageId: string;
  threadId: string | null;
  // "outbound" = SENT FROM one of the requested addresses (our own answer, e.g.
  // staff replying from Gmail via send-as); "inbound" = sent TO one of them by
  // someone else. A message from a requested address is always outbound, even
  // when it is also addressed to one (alias to alias).
  direction: "inbound" | "outbound";
  // RFC 5322 identifiers, verbatim (angle brackets kept).
  messageId: string | null;
  inReplyTo: string | null;
  references: string[];
  fromEmail: string | null;
  fromName: string | null;
  to: string[];
  cc: string[];
  // Which of the requested addresses (or addresses at a requested domain) the
  // message was sent to.
  matchedRecipients: string[];
  subject: string | null;
  sentAt: string | null;
  labels: string[];
  automation: AutomationHeaders;
  // MIME type of the message's top part (multipart/report = a delivery report).
  mimeType: string | null;
  bodyText: string | null;
  bodyStatus: BodyStatus;
}

export interface AddressedMessagesPage {
  mailboxes: string[];
  messages: AddressedMessage[];
  nextCursor: string | null;
}

export type AddressedMessagesResult =
  | { found: true; page: AddressedMessagesPage }
  | { found: false; reason: "no_staff_mailbox_connected" };

export class AddressedMessagesInputError extends Error {}

const normAddress = (a: string): string => a.trim().toLowerCase();
const normDomain = (d: string): string => d.trim().toLowerCase().replace(/^@+/, "");

const STAFF_DOMAINS = new Set(STAFF_ADDRESSES.map((a) => a.split("@")[1]));

export const normalizeFilter = (
  input: AddressedMessagesInput
): { addresses: string[]; domains: string[] } => {
  const addresses = [...new Set((input.addresses ?? []).map(normAddress).filter((a) => a.length > 0))];
  const domains = [...new Set((input.domains ?? []).map(normDomain).filter((d) => d.length > 0))];

  if (addresses.length === 0 && domains.length === 0) {
    throw new AddressedMessagesInputError("at least one address or domain is required");
  }
  if (addresses.length > MAX_ADDRESSES) {
    throw new AddressedMessagesInputError(`at most ${MAX_ADDRESSES} addresses`);
  }
  if (domains.length > MAX_DOMAINS) {
    throw new AddressedMessagesInputError(`at most ${MAX_DOMAINS} domains`);
  }
  const staffAddress = addresses.find((a) => STAFF_ADDRESSES.includes(a));
  if (staffAddress) {
    throw new AddressedMessagesInputError(`${staffAddress} is a staff address, not a sending mailbox`);
  }
  const staffDomain = domains.find((d) => STAFF_DOMAINS.has(d));
  if (staffDomain) {
    throw new AddressedMessagesInputError(`${staffDomain} is a staff mailbox domain, not a sending domain`);
  }
  return { addresses, domains };
};

// Opaque cursor = the silver row id of the last message served (keyset on the
// primary key: a total order that includes messages without a date).
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
export const encodeCursor = (id: string): string => Buffer.from(id, "utf-8").toString("base64url");
export const decodeCursor = (cursor: string): string => {
  const id = Buffer.from(cursor, "base64url").toString("utf-8");
  if (!UUID_RE.test(id)) throw new AddressedMessagesInputError("invalid cursor");
  return id;
};

type AnyRecord = Record<string, unknown>;

const headerReader = (message: GmailMessage | null) => {
  const payload = ((message?.payload as AnyRecord | undefined) ?? {}) as AnyRecord;
  const headers = Array.isArray(payload.headers) ? (payload.headers as AnyRecord[]) : [];
  return (name: string): string | null => {
    const lower = name.toLowerCase();
    const found = headers.find((h) => typeof h?.name === "string" && (h.name as string).toLowerCase() === lower);
    const v = found?.value;
    return typeof v === "string" && v.trim().length > 0 ? v.trim() : null;
  };
};

// "<a@x> <b@y>" (possibly folded over lines) → ["<a@x>", "<b@y>"]. A value
// without angle brackets is split on whitespace rather than dropped.
export const parseMessageIdList = (raw: string | null): string[] => {
  if (!raw) return [];
  const bracketed = raw.match(/<[^<>\s]+>/g);
  if (bracketed && bracketed.length > 0) return bracketed;
  return raw.split(/\s+/).filter((t) => t.length > 0);
};

const firstMessageId = (raw: string | null): string | null => parseMessageIdList(raw)[0] ?? null;

export interface SilverRow {
  id: string;
  google_account_id: string;
  org_id: string;
  gmail_message_id: string;
  thread_id: string | null;
  from_email: string | null;
  from_name: string | null;
  to_emails: string[] | null;
  cc_emails: string[] | null;
  subject: string | null;
  sent_at: Date | null;
  labels: string[] | null;
}

// Bronze payloads of ONE served page, keyed `${org_id}:${gmail_message_id}`
// (detoasted only for the rows actually returned).
export const loadPayloads = async (
  rows: Pick<SilverRow, "org_id" | "gmail_message_id">[]
): Promise<Map<string, GmailMessage>> => {
  const payloads = new Map<string, GmailMessage>();
  if (rows.length === 0) return payloads;
  const raw = await query(
    `SELECT m.org_id, m.gmail_message_id, m.payload
       FROM gmail_messages_raw m
       JOIN unnest($1::text[], $2::text[]) AS k(org_id, gmail_message_id)
         ON m.org_id = k.org_id AND m.gmail_message_id = k.gmail_message_id`,
    [rows.map((r) => r.org_id), rows.map((r) => r.gmail_message_id)]
  );
  for (const r of raw.rows) {
    payloads.set(`${r.org_id}:${r.gmail_message_id}`, r.payload as GmailMessage);
  }
  return payloads;
};

// One silver row + its payload → the served message. Shared by the staff read
// and the org read so one consumer parser reads both.
export const shapeAddressedMessage = <D extends string>(
  r: SilverRow,
  message: GmailMessage | null,
  mailbox: string,
  direction: D,
  isRequested: (address: string) => boolean
): Omit<AddressedMessage, "direction"> & { direction: D } => {
  const header = headerReader(message);
  const body = extractMessageBody(message);
  const to = Array.isArray(r.to_emails) ? r.to_emails : [];
  const cc = Array.isArray(r.cc_emails) ? r.cc_emails : [];
  const topPart = (message?.payload as AnyRecord | undefined) ?? {};
  return {
    id: `${mailbox}:${r.gmail_message_id}`,
    mailbox,
    gmailMessageId: r.gmail_message_id,
    threadId: r.thread_id,
    direction,
    messageId: firstMessageId(header("Message-ID")),
    inReplyTo: firstMessageId(header("In-Reply-To")),
    references: parseMessageIdList(header("References")),
    fromEmail: r.from_email,
    fromName: r.from_name,
    to,
    cc,
    matchedRecipients: [...new Set([...to, ...cc].filter(isRequested))],
    subject: r.subject,
    sentAt: r.sent_at instanceof Date ? r.sent_at.toISOString() : null,
    labels: Array.isArray(r.labels) ? r.labels : [],
    automation: {
      autoSubmitted: header("Auto-Submitted"),
      precedence: header("Precedence"),
      xAutoreply: header("X-Autoreply"),
      xAutorespond: header("X-Autorespond"),
      xAutoResponseSuppress: header("X-Auto-Response-Suppress"),
      xAutogenerated: header("X-Autogenerated"),
      xFailedRecipients: header("X-Failed-Recipients"),
      listId: header("List-Id"),
      listUnsubscribe: header("List-Unsubscribe"),
      returnPath: header("Return-Path"),
      contentType: header("Content-Type"),
    },
    mimeType: typeof topPart.mimeType === "string" ? (topPart.mimeType as string) : null,
    bodyText: body.text,
    bodyStatus: body.status,
  };
};

export const getAddressedMessages = async (
  input: AddressedMessagesInput
): Promise<AddressedMessagesResult> => {
  const { addresses, domains } = normalizeFilter(input);
  const afterId = input.cursor ? decodeCursor(input.cursor) : null;
  const limit = input.limit ?? DEFAULT_PAGE_LIMIT;
  const staff = [...STAFF_ADDRESSES];

  const accounts = await query(
    `SELECT id, org_id, lower(google_account_email) AS email
       FROM google_oauth_tokens
      WHERE lower(google_account_email) = ANY($1::text[])`,
    [staff]
  );
  if (accounts.rows.length === 0) return { found: false, reason: "no_staff_mailbox_connected" };

  const mailboxById = new Map<string, string>(
    accounts.rows.map((r) => [r.id as string, r.email as string])
  );
  const accountIds = [...mailboxById.keys()];
  const orgIds = [...new Set(accounts.rows.map((r) => r.org_id as string))];

  // Page of matching silver rows first (no payload): the scan walks the primary
  // key and only the served rows ever detoast their bronze payload.
  const page = await query(
    `SELECT s.id, s.google_account_id, s.org_id, s.gmail_message_id, s.thread_id,
            s.from_email, s.from_name, s.to_emails, s.cc_emails, s.subject, s.sent_at, s.labels
       FROM gmail_messages_silver s
      WHERE s.org_id = ANY($1::text[])
        AND s.google_account_id = ANY($2::uuid[])
        AND (
              s.from_email = ANY($3::text[])
           OR split_part(s.from_email, '@', 2) = ANY($4::text[])
           OR EXISTS (
                SELECT 1 FROM jsonb_array_elements_text(s.to_emails || s.cc_emails) AS r(addr)
                 WHERE r.addr = ANY($3::text[]) OR split_part(r.addr, '@', 2) = ANY($4::text[])
              )
            )
        AND ($5::uuid IS NULL OR s.id > $5::uuid)
        AND ($6::timestamptz IS NULL OR s.sent_at >= $6::timestamptz)
        AND ($7::timestamptz IS NULL OR s.sent_at < $7::timestamptz)
      ORDER BY s.id
      LIMIT $8`,
    [orgIds, accountIds, addresses, domains, afterId, input.since ?? null, input.until ?? null, limit + 1]
  );

  const hasMore = page.rows.length > limit;
  const rows = (hasMore ? page.rows.slice(0, limit) : page.rows) as unknown as SilverRow[];

  const payloads = await loadPayloads(rows);

  const addressSet = new Set(addresses);
  const domainSet = new Set(domains);
  const isRequested = (a: string) => addressSet.has(a) || domainSet.has(a.split("@")[1] ?? "");

  const messages = rows.map((r) =>
    shapeAddressedMessage(
      r,
      payloads.get(`${r.org_id}:${r.gmail_message_id}`) ?? null,
      mailboxById.get(r.google_account_id) ?? "",
      r.from_email !== null && isRequested(r.from_email) ? "outbound" : "inbound",
      isRequested
    )
  );

  return {
    found: true,
    page: {
      mailboxes: [...new Set(mailboxById.values())].sort(),
      messages,
      nextCursor: hasMore ? encodeCursor(rows[rows.length - 1].id) : null,
    },
  };
};
